import { crc32, deflateRawSync } from 'node:zlib';

/** One entry of a zip a spec builds. */
export interface FakeZipEntry {
  readonly name: string;
  readonly data: string | Uint8Array;
  /** Default `deflate`. */
  readonly method?: 'store' | 'deflate';
  /** Lies about the size in the central directory (a zip-bomb probe). */
  readonly declaredSize?: number;
}

/** A zip archive in memory: local headers, data, central directory, end record — enough for `readSkillZip`. */
export function buildZip(entries: readonly FakeZipEntry[]): Buffer {
  const locals: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const entry of entries) {
    const name = Buffer.from(entry.name, 'utf8');
    const raw = Buffer.from(typeof entry.data === 'string' ? Buffer.from(entry.data, 'utf8') : entry.data);
    const method = entry.method === 'store' ? 0 : 8;
    const packed = method === 0 ? raw : deflateRawSync(raw);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(method, 8);
    local.writeUInt32LE(crc32(raw), 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26);
    locals.push(local, name, packed);
    const head = Buffer.alloc(46);
    head.writeUInt32LE(0x02014b50, 0);
    head.writeUInt16LE(20, 4);
    head.writeUInt16LE(20, 6);
    head.writeUInt16LE(method, 10);
    head.writeUInt32LE(crc32(raw), 16);
    head.writeUInt32LE(packed.length, 20);
    head.writeUInt32LE(entry.declaredSize ?? raw.length, 24);
    head.writeUInt16LE(name.length, 28);
    head.writeUInt32LE(offset, 42);
    central.push(head, name);
    offset += 30 + name.length + packed.length;
  }
  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
